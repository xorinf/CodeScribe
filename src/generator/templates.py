def _visibility_badge(visibility: Visibility) -> str:
    """Return a short label for a visibility level.

    Args:
        visibility: The Visibility enum value.

    Returns:
        A formatted string like "(public)", "(private)", etc.
    """
    return "({})".format(visibility.value)


def _format_param_signature(params: list[Parameter]) -> str:
    """Format a parameter list into a function signature string.

    Args:
        params: Ordered list of Parameter objects.

    Returns:
        A string like "x: int, y: str = 'hello'" or "()" if empty.
    """
    if not params:
        return "()"
    parts = []
    for p in params:
        s = p.name
        if p.type_hint:
            s += ": {}".format(p.type_hint)
        if p.default_value:
            s += " = {}".format(p.default_value)
        parts.append(s)
    return "({})".format(", ".join(parts))


def _format_decorators(decorators: list[str]) -> str:
    """Format a list of decorators as prefixed lines.

    Args:
        decorators: List of decorator name strings.

    Returns:
        Formatted decorator lines or empty string.
    """
    if not decorators:
        return ""
    lines = ["@{}".format(d) for d in decorators]
    return "\n".join(lines) + "\n"


def _docstring_summary(docstring: Optional[str]) -> str:
    """Extract the first line of a docstring as a summary.

    Args:
        docstring: The full docstring text, or None.

    Returns:
        The first non-empty line, or "No description provided."
    """
    if not docstring:
        return "No description provided."
    for line in docstring.strip().splitlines():
        stripped = line.strip()
        if stripped:
            return stripped
    return "No description provided."


def _indent(text: str, level: int = 1) -> str:
    """Indent every line of text by the given number of levels.

    Args:
        text: The text to indent.
        level: Number of indentation levels (each = 4 spaces).

    Returns:
        The indented text.
    """
    prefix = "    " * level
    return "\n".join(prefix + line for line in text.splitlines())


